// Isolated local fixture only. Never writes to Supabase or deployed websites.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const origin = process.env.THEME_TEST_ORIGIN || 'http://localhost:3110';
assert(['localhost', '127.0.0.1'].includes(new URL(origin).hostname));
(async () => {
  const browser = await chromium.launch({executablePath: '/usr/bin/chromium', args: ['--no-sandbox']});
  const context = await browser.newContext({viewport: {width: 390, height: 844}});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => {if (message.type() === 'error' && /hydration|Minified React error/i.test(message.text())) errors.push(message.text());});
  try {
    await page.goto(origin + '/auth', {waitUntil: 'networkidle'});
    await page.locator('#auth-email').fill('member@example.test');
    await page.locator('#auth-password').fill('test-only-password');
    await page.getByRole('combobox', {name: 'Choose language'}).selectOption('zh-CN');
    assert.equal(await page.locator('html').getAttribute('lang'), 'zh-CN');
    assert.equal(await page.locator('#auth-email').inputValue(), 'member@example.test');
    assert.equal(await page.locator('#auth-password').inputValue(), 'test-only-password');
    await page.locator('form').getByRole('button', {name: '登录', exact: true}).waitFor();
    await page.reload({waitUntil: 'networkidle'});
    assert.equal(await page.locator('html').getAttribute('lang'), 'zh-CN');
    const html = await (await context.request.get(origin + '/auth')).text();
    assert.match(html, /lang="zh-CN"/);
    assert.match(html, /准备好开启下一段旅程了吗/);
    await page.locator('#auth-email').fill('member@example.test');
    await page.locator('#auth-password').fill('test-only-password');
    await page.locator('form').getByRole('button', {name: '登录', exact: true}).click();
    await page.waitForURL('**/dashboard');
    await page.goto(origin + '/flights/new', {waitUntil: 'networkidle'});
    const notes = page.locator('textarea');
    await notes.fill('User text: Save / 保存 is NOT a translation key');
    await page.getByRole('combobox', {name: '选择语言'}).selectOption('en');
    await page.waitForFunction(() => !document.querySelector('select[aria-label="Choose language"]')?.disabled);
    assert.equal(await notes.inputValue(), 'User text: Save / 保存 is NOT a translation key');
    await page.evaluate(() => window.scrollTo({top: 0, behavior: 'instant'}));
    await page.waitForFunction(() => window.scrollY === 0);
    await page.getByRole('button', {name: 'Choose color theme'}).click();
    await page.getByRole('radio', {name: 'Dark', exact: true}).click();
    await page.getByRole('combobox', {name: 'Choose language'}).selectOption('zh-CN');
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
    assert.equal(await notes.inputValue(), 'User text: Save / 保存 is NOT a translation key');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path: '/tmp/flightdesk-i18n-mobile-dark.png', fullPage: true});
    for (const route of ['/profile', '/settings', '/roadmap', '/flights/44444444-4444-4444-8444-444444444444/edit']) {
      await page.goto(origin + route, {waitUntil: 'networkidle'});
      assert.equal(await page.locator('html').getAttribute('lang'), 'zh-CN');
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, route);
    }
    await page.goto(origin + '/admin/translations', {waitUntil: 'networkidle'});
    assert.equal(await page.locator('textarea').count(), 0, 'ordinary user cannot edit overrides');
    const admin = await browser.newContext({viewport: {width: 1440, height: 1000}});
    const ap = await admin.newPage();
    ap.on('pageerror', error => errors.push(error.message));
    await ap.goto(origin + '/auth', {waitUntil: 'networkidle'});
    await ap.locator('#auth-email').fill('admin@example.test');
    await ap.locator('#auth-password').fill('test-only-password');
    await ap.locator('form').getByRole('button', {name: 'Sign in', exact: true}).click();
    await ap.waitForURL('**/dashboard');
    await ap.goto(origin + '/admin/translations', {waitUntil: 'networkidle'});
    await ap.getByRole('textbox', {name: 'Search keys, English or Chinese'}).fill('common.save');
    let entry = ap.locator('article').filter({has: ap.getByRole('textbox', {name: 'common.save', exact: true})});
    await entry.getByRole('textbox', {name: 'common.save', exact: true}).fill('保存测试译文');
    await entry.getByRole('button', {name: 'Save and apply', exact: true}).click();
    await ap.getByRole('status').filter({hasText: 'Translation saved and applied.'}).waitFor();
    const published = await (await context.request.get(origin + '/api/translations')).json();
    assert.equal(published.overrides['common.save'], '保存测试译文');
    await ap.getByRole('combobox', {name: 'Choose language'}).selectOption('zh-CN');
    await ap.goto(origin + '/settings', {waitUntil: 'networkidle'});
    await ap.getByRole('button', {name: '编辑显示名称'}).click();
    await ap.getByRole('button', {name: '保存测试译文', exact: true}).waitFor();
    await ap.goto(origin + '/admin/translations', {waitUntil: 'networkidle'});
    await ap.getByRole('textbox', {name: '搜索 Key、英文或中文'}).fill('common.save');
    entry = ap.locator('article').filter({has: ap.getByRole('textbox', {name: 'common.save', exact: true})});
    ap.once('dialog', dialog => dialog.accept());
    await entry.getByRole('button', {name: '恢复默认', exact: true}).click();
    await ap.getByRole('status').filter({hasText: '已恢复默认译文。'}).waitFor();
    const reset = await (await context.request.get(origin + '/api/translations')).json();
    assert.equal(reset.overrides['common.save'], undefined);
    await admin.close();
    assert.deepEqual(errors, []);
    console.log('PASS locale switch, SSR cookie, reload, Auth, dirty forms/user content, theme independence, mobile routes and hydration');
    console.log('PASS admin override save, public visibility, cross-page application, reset and ordinary-user denial against local fixtures');
  } finally {await context.close(); await browser.close();}
})().catch(error => {console.error(error); process.exitCode = 1;});
